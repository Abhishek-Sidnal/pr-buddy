const MAX_COOKIE_HEADER_LENGTH = 8_192;

export interface CookieNames {
  readonly session: string;
  readonly state: string;
  /** Whether cookies carry `Secure`. False only for plain HTTP on the local machine. */
  readonly isSecure: boolean;
}

/**
 * Cookie names for the dashboard's origin. Over HTTPS they carry the `__Host-` prefix, which
 * makes a browser refuse them unless they are `Secure`, have `Path=/` and no `Domain`: another
 * subdomain cannot plant or overwrite them.
 */
export function cookieNamesFor(publicUrl: string): CookieNames {
  const isSecure = new URL(publicUrl).protocol === "https:";
  const prefix = isSecure ? "__Host-" : "";
  return { session: `${prefix}prbuddy_session`, state: `${prefix}prbuddy_state`, isSecure };
}

/**
 * Reads one cookie from a `Cookie` header. Returns `undefined` when it is absent. A header that
 * is unreasonably long is ignored whole.
 */
export function readCookie(header: string | undefined, name: string): string | undefined {
  if (header === undefined || header.length > MAX_COOKIE_HEADER_LENGTH) {
    return undefined;
  }
  for (const part of header.split(";")) {
    const separator = part.indexOf("=");
    if (separator !== -1 && part.slice(0, separator).trim() === name) {
      return part.slice(separator + 1).trim();
    }
  }
  return undefined;
}

/**
 * Builds a `Set-Cookie` value. Values are base64url tokens generated by this service, so they
 * need no encoding. `HttpOnly` keeps scripts away from it; `SameSite=Lax` keeps other sites from
 * sending it with anything but a top-level navigation.
 */
export function serializeCookie(
  names: CookieNames,
  name: string,
  value: string,
  maxAgeSeconds: number,
): string {
  return [
    `${name}=${value}`,
    "Path=/",
    `Max-Age=${maxAgeSeconds}`,
    "HttpOnly",
    "SameSite=Lax",
    ...(names.isSecure ? ["Secure"] : []),
  ].join("; ");
}

/** A `Set-Cookie` value that makes the browser forget a cookie. */
export function clearCookie(names: CookieNames, name: string): string {
  return serializeCookie(names, name, "", 0);
}
